#!/usr/bin/env python3
"""Download the curated photos, resize them for the web and write data/photos.js.

Usage: python3 tools/photos/build.py

Reads tools/photos/selection.json: { species_key: [ {id, ext, license, by, taxon, obs}, ... ] }
Writes img/<photo id>.webp and data/photos.js. Already-built images are skipped.
"""
import json
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from PIL import Image, ImageOps

import s3

ROOT = Path(__file__).resolve().parents[2]
SELECTION = Path(__file__).resolve().parent / "selection.json"
IMG_DIR = ROOT / "img"
OUT = ROOT / "data" / "photos.js"
LONG_EDGE = 900
QUALITY = 72


def build_image(photo):
    dest = IMG_DIR / f"{photo['id']}.webp"
    if dest.exists():
        return True
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / f"src.{photo['ext']}"
        if not s3.download(photo["id"], photo["ext"], "large", src):
            print(f"failed to download {photo['id']}")
            return False
        with Image.open(src) as im:
            im = ImageOps.exif_transpose(im).convert("RGB")
            im.thumbnail((LONG_EDGE, LONG_EDGE), Image.Resampling.LANCZOS)
            im.save(dest, "WEBP", quality=QUALITY, method=6)
    return True


def main():
    selection = json.loads(SELECTION.read_text())
    IMG_DIR.mkdir(exist_ok=True)
    photos = [p for ps in selection.values() for p in ps]
    with ThreadPoolExecutor(12) as ex:
        ok = list(ex.map(build_image, photos))
    if not all(ok):
        raise SystemExit("Some photos failed to download; re-run to retry.")

    keep = {f"{p['id']}.webp" for p in photos}
    for f in IMG_DIR.glob("*.webp"):
        if f.name not in keep:
            f.unlink()

    data = {
        species: [{"id": p["id"], "by": p["by"], "license": p["license"], "taxon": p["taxon"]} for p in ps]
        for species, ps in sorted(selection.items())
    }
    body = json.dumps(data, indent=2, ensure_ascii=False)
    OUT.write_text(
        "// Generated by tools/photos/build.py from tools/photos/selection.json. Do not edit by hand.\n"
        f"export const PHOTOS = {body};\n"
    )
    print(f"{len(photos)} photos for {len(data)} species -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
